# The codec of every Logstash file input: plain (30-decode.conf parses JSON after the source file went to
# t-pot_log_path, Heralding's CSV is split by its parse file) in ISO-8859-1, which keeps every byte; with
# UTF-8 Logstash would turn a line with an invalid byte into escaped text no JSON parser takes.
# 12-files.conf makes UTF-8 of it again, an invalid byte U+FFFD as Fluent Bit sends it from a SENSOR
CODEC = 'plain { charset => "ISO-8859-1" }'


def logstash_inputs() -> str:
    """10-input-files.conf: one file input per entry of INPUTS, in their order."""
    lines = [HEADER.rstrip("\n"), "# The file inputs of the pipeline files (12-files.conf hands their events on).",
             "input {", ""]
    for entry in INPUTS:
        paths = ", ".join(f'"{path}"' for path in entry.paths)
        # events written before Logstash starts are kept; it counts only for a file the sincedb (in the
        # container layer) does not know
        lines += [f"# {entry.type}", "  file {", f"    path => [{paths}]", '    start_position => "beginning"',
                  f"    codec => {CODEC}", f'    type => "{entry.type}"', "  }", ""]
    lines.append("}")
    return "\n".join(lines) + "\n"


def logstash_decode() -> str:
    """30-decode.conf: the source file into t-pot_log_path, then the lines of the JSON types parsed."""
    types = [entry.type for entry in INPUTS if entry.decode == "json"]
    lines = [HEADER.rstrip("\n"),
             "# The first filter of the processing pipeline. The file input names the file it read in [path]",
             "# (its events carry nothing else yet): it goes to t-pot_log_path, a t-pot_log_path the event",
             "# brings (a sensor's) stays, so [path] is left to the honeypots. A line of a JSON type is",
             "# parsed into the event: its keys win over those of the input; a line that is no JSON stays",
             "# in message with the tag _jsonparsefailure, a blank one is no event (as with the json codec).",
             "# The raw line is in [@metadata][raw].",
             "filter {",
             "  if [path] and ![t-pot_log_path] {",
             "    mutate {",
             '      rename => { "path" => "t-pot_log_path" }',
             "    }",
             "  }",
             "  if [type] in ["]
    lines += [f'    "{name}"' + ("," if number < len(types) - 1 else "") for number, name in enumerate(types)]
    lines += ["  ] {",
              "    mutate {",
              '      rename => { "message" => "[@metadata][raw]" }',
              "    }",
              "    if [@metadata][raw] =~ /\\A\\s*\\z/ {",
              "      drop {}",
              "    }",
              "    json {",
              '      source => "[@metadata][raw]"',
              "    }",
              '    if "_jsonparsefailure" in [tags] {',
              "      mutate {",
              '        copy => { "[@metadata][raw]" => "message" }',
              "      }",
              "    }",
              "  }",
              "}"]
    return "\n".join(lines) + "\n"


def fluentbit_inputs() -> str:
    """inputs.yaml of Fluent Bit (a SENSOR): one tail input per entry of INPUTS, in their order. The
    line goes raw (key log) with the file it came from (t-pot_log_path), the HIVE decodes it. Each
    input has its own offsets db: at its init a tail input deletes the rows of every inode it does not
    watch, a shared db would lose the offsets of the others on a restart of the container."""
    lines = [HEADER.rstrip("\n"), "# The tail inputs of fluent-bit.yaml; tpot.lua turns the tag into the type.",
             "pipeline:", "  inputs:"]
    slugs = [re.sub(r"[^a-z0-9_-]", "-", entry.type.lower()) for entry in INPUTS]
    if len(set(slugs)) != len(slugs):
        raise ValueError(f"two inputs share an offsets db: {slugs}")
    for entry, slug in zip(INPUTS, slugs):
        lines += [f"    # {entry.type}",
                  "    - name: tail",
                  f"      tag: tpot.{entry.type}",
                  f"      path: {','.join(entry.paths)}",
                  "      path_key: t-pot_log_path",
                  "      key: log",
                  "      read_from_head: true",
                  f"      db: /data/fluentbit/offsets.db.{slug}",
                  "      db.locking: true",
                  "      skip_long_lines: on",
                  "      buffer_chunk_size: 64k",
                  "      buffer_max_size: 1M",
                  "      refresh_interval: 10",
                  "      storage.type: filesystem"]
    return "\n".join(lines) + "\n"


# Generated file -> its text
TARGETS: Dict[Path, Callable[[], str]] = {
    PIPELINE_DIR / "10-input-files.conf": logstash_inputs,
    PIPELINE_DIR / "30-decode.conf": logstash_decode,
    FLUENTBIT_DIR / "inputs.yaml": fluentbit_inputs,
}


def main(argv: Optional[List[str]] = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if argv not in ([], ["--check"]):
        print("usage: python3 -m tpotctl.logs_config [--check]", file=sys.stderr)
        return 2
    stale = []
    for path, generate in TARGETS.items():
        text = generate()
        try:
            same = path.read_text(encoding="utf-8") == text
        except OSError:
            same = False
        if same:
            continue
        stale.append(path)
        if not argv:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if argv and stale:
        for path in stale:
            print(f"{path.relative_to(REPO)} is not the generated one, run python3 -m tpotctl.logs_config",
                  file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
