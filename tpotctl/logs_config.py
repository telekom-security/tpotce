"""The log table of T-Pot: the one source of the file inputs of Logstash and of Fluent Bit.

INPUTS names, per Logstash type, the log files of a honeypot (or NSM tool) under the data folder
(TPOT_DATA_PATH, /data in Logstash and Fluent Bit) and how a line of them is decoded. TARGETS are the
files written from it (the file inputs and the decoding of the processing pipeline, the tail inputs of
Fluent Bit on a SENSOR); the tests run --check:

    python3 -m tpotctl.logs_config [--check]
"""

